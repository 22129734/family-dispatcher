ORDER = [*GROUPS, OTHER]

# Порядок проверки: сначала длинные основы — «сливочное масло» раньше «масло»,
# «печенье» раньше «печень»
_STEMS = sorted(
    ((stem, group) for group, stems in GROUPS.items() for stem in stems),
    key=lambda pair: -len(pair[0]),
)


def rule_group(text: str) -> str | None:
    """Отдел по словарю или None, если слово незнакомое."""
    lowered = " " + re.sub(r"\s+", " ", text.lower()) + " "
    for stem, group in _STEMS:
        # Основа — с начала слова: «сок» не должен находиться в «носок»
        if re.search(r"(?<![а-яёa-z])" + re.escape(stem), lowered):
            return group
    return None


def with_groups(items: list[dict]) -> list[dict]:
    """Проставить отдел по словарю тем пунктам, у которых его ещё нет."""
    if all(item.get("group") for item in items):
        return [dict(item) for item in items]
    with telemetry.track_call(telemetry.Kind.CATALOG, "group"):
        return [{**item, "group": item.get("group") or rule_group(item["text"])} for item in items]


def needs_llm(items: list[dict]) -> bool:
    return any(not item.get("group") for item in items)


def fill_groups(task_id: str, client: LLMClient | None = None) -> None:
    """Фоном: модель раскладывает по отделам то, что не узнал словарь."""
    with SessionLocal() as db:
        task = db.get(TaskRow, task_id)
        if task is None or not needs_llm(task.items or []):
            return
        unknown = [item["text"] for item in task.items if not item.get("group")]
        answer = (client or LLMClient()).group_items(unknown, ORDER)
        if not answer:
            return
        task.items = [
            {**item, "group": item.get("group") or _valid(answer.get(item["text"]))}
            for item in task.items
        ]
        db.commit()


def _valid(group: str | None) -> str:
    return group if group in ORDER else OTHER
