"""Несколько дел в одном сообщении — расписание секции и список."""

from datetime import datetime

from app.services import multi_tasks

NOW = datetime(2026, 10, 12, 10, 0)  # понедельник

SCHEDULE = """Расписание на неделю
(12.10-18.10)

ПОНЕДЕЛЬНИК
Выходной 

ВТОРНИК
Зал в 17:45-18:45 (2 группа + 2022)
(База на Тутаевском шоссе)

Зал в 19:00-20:00 (1 группа)

СРЕДА
Зал в 18:00-19:15 
(База на Тутаевском шоссе)
Приходят только 2021 год

ЧЕТВЕРГ
Лёд в 16:30-18:00
(Дс Торпедо)

ПЯТНИЦА
Лёд в 16:30-18:00
(Дс Торпедо)

СУББОТА
Лёд в 14:15-15:45
(Газпром)

ВОСКРЕСЕНЬЕ
Лёд в 9:30-11:00 
1 группа 
(Газпром)

Лёд в 11:15-12:45
2 группа + 2022
(Газпром)
"""


def test_week_schedule_becomes_eight_tasks() -> None:
    items = multi_tasks.split(SCHEDULE, NOW)
    got = [
        (i.title, i.due_at.strftime("%d.%m %H:%M"), i.ends_at.strftime("%H:%M"), i.note)
        for i in items
    ]
    assert got == [
        ("Зал", "13.10 17:45", "18:45", "2 группа + 2022; База на Тутаевском шоссе"),
        ("Зал", "13.10 19:00", "20:00", "1 группа"),
        ("Зал", "14.10 18:00", "19:15", "База на Тутаевском шоссе; Приходят только 2021 год"),
        ("Лёд", "15.10 16:30", "18:00", "Дс Торпедо"),
        ("Лёд", "16.10 16:30", "18:00", "Дс Торпедо"),
        ("Лёд", "17.10 14:15", "15:45", "Газпром"),
        ("Лёд", "18.10 09:30", "11:00", "1 группа; Газпром"),
        ("Лёд", "18.10 11:15", "12:45", "2 группа + 2022; Газпром"),
    ]


def test_schedule_pasted_in_one_line() -> None:
    flat = " ".join(SCHEDULE.split())
    items = multi_tasks.split(flat, NOW)
    assert len(items) == 8
    assert items[1].title == "Зал" and items[1].due_at.strftime("%d.%m %H:%M") == "13.10 19:00"


def test_bullet_list_and_single_task() -> None:
    items = multi_tasks.split("- купить хлеб\n- завтра в 19 забрать Машу\n- оплатить свет", NOW)
    assert [i.title for i in items] == ["купить хлеб", "завтра в 19 забрать Машу", "оплатить свет"]
    assert items[1].due_at == datetime(2026, 10, 13, 19, 0)
    assert multi_tasks.split("Олег, завтра в 19 забери Машу", NOW) == []
